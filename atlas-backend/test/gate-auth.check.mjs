// The SSH-key gate's authentication and proxy rules, executed - not read.
//
// WHY THIS FILE EXISTS. gate.js was the last service in the backend with no
// behavioral test, and it is the one that decides who reaches /docker, /db,
// /git and /shell on the console host - i.e. the Docker socket, which is root
// on the box. Passes 11 and 12 both deferred it for exactly that reason ("an
// auth path, give it a pass that starts early"). This is that pass.
//
// It also pins the bug this pass found and fixed: the "wrong namespace" error
// quoted a field read straight out of the pasted signature blob into the page
// unescaped. That field is attacker-chosen and needs NO KEY to construct -
// parseSignature is reached before any signature verification happens. Arm
// "the rejection message cannot inject markup" is the regression test.
//
// SIGNATURES HERE ARE REAL. They are produced by the actual `ssh-keygen -Y
// sign` binary against keys generated by `ssh-keygen -t ed25519`, not built by
// re-implementing SSHSIG in the test. Do not "simplify" that into a hand-rolled
// blob: hand-rolling shares any construction mistake with lib/sshsig.js, and
// then the happy path passes for the wrong reason. (The hand-rolled blob that
// IS here is deliberate - it exists only to reach the parser with a namespace
// no honest signer would produce.)
//
// The gate's own listener is not used; the exported handleRequest/handleUpgrade
// are mounted on a server bound to an ephemeral port, so this file cannot
// collide with a gate actually running on 8099.
//
// Run: node test/gate-auth.check.mjs
import { strictEqual, ok } from 'node:assert'
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import http from 'node:http'
import net from 'node:net'

let failures = 0
const check = async (name, fn) => {
  try { await fn(); console.log('ok', name) }
  catch (e) { failures++; console.error('FAIL', name, '-', e.message) }
}

// ---- real keys, real signatures --------------------------------------------
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'gate-check-'))
const keygen = (name) =>
  execFileSync('ssh-keygen', ['-q', '-t', 'ed25519', '-N', '', '-C', name, '-f', path.join(dir, name)])
keygen('trusted')
keygen('untrusted')
const KEYS = path.join(dir, 'authorized_keys')
// A comment line and a blank line, because allowedKeys() filters both and a
// regression there would silently trust nothing (or try to parse a comment).
fs.writeFileSync(KEYS, `# atlas\n\n${fs.readFileSync(path.join(dir, 'trusted.pub'), 'utf8')}`)

const sign = (message, key = 'trusted', ns = 'atlas-gate') =>
  execFileSync('ssh-keygen', ['-Y', 'sign', '-f', path.join(dir, key), '-n', ns, '-'],
    { input: message }).toString()

// Env must be set before the module is imported: PORT, KEYS_FILE and SECRET are
// all read at module scope.
process.env.GATE_KEYS = KEYS
process.env.GATE_SECRET = 'test-secret-not-a-real-one'
const { handleRequest, handleUpgrade, gateSecret } = await import('../services/gate.js')
const { issueToken, tokenValid } = await import('../lib/sshsig.js')

// ---- the gate under test ----------------------------------------------------
const gate = http.createServer(handleRequest)
gate.on('upgrade', handleUpgrade)
await new Promise((r) => gate.listen(0, '127.0.0.1', r))
const PORT = gate.address().port

// ---- a stand-in for the dev server on 5173 ----------------------------------
// UPSTREAM is a module constant, so the dev host really does resolve to 5173;
// the test binds it rather than pretending. Started on demand so the
// "upstream is down" arm can observe the real 502.
let upstream = null
const seen = []
const startUpstream = () => new Promise((r) => {
  upstream = http.createServer((req, res) => {
    seen.push({ url: req.url, headers: req.headers })
    res.writeHead(200, { 'content-type': 'text/plain' })
    res.end('DEV SERVER PAYLOAD')
  })
  upstream.on('upgrade', (req, socket) => {
    seen.push({ url: req.url, headers: req.headers, upgrade: true })
    socket.write('HTTP/1.1 101 Switching Protocols\r\nupgrade: websocket\r\n\r\nHELLO-WS')
  })
  upstream.listen(5173, '127.0.0.1', r)
})
const stopUpstream = () => { upstream?.closeAllConnections(); upstream?.close(); upstream = null }

// ---- helpers ----------------------------------------------------------------
const DEV = 'dev.myatlasapp.net'
const req = (opts = {}, body) => new Promise((res, rej) => {
  const r = http.request({ host: '127.0.0.1', port: PORT, method: 'GET', path: '/', ...opts,
    headers: { host: DEV, ...(opts.headers || {}) } }, (r2) => {
    let b = ''
    r2.setEncoding('utf8')
    r2.on('data', (c) => { b += c })
    r2.on('end', () => res({ status: r2.statusCode, headers: r2.headers, body: b }))
  })
  r.on('error', rej)
  if (body != null) r.write(body)
  r.end()
})
const post = (form, headers = {}) => {
  const b = new URLSearchParams(form).toString()
  return req({ method: 'POST', path: '/_gate/verify',
    headers: { 'content-type': 'application/x-www-form-urlencoded', 'content-length': Buffer.byteLength(b), ...headers } }, b)
}
const nonceFrom = (html) => {
  const m = html.match(/name="nonce" value="([^"]*)"/)
  ok(m, 'challenge page carried no nonce')
  return m[1]
}
const freshNonce = async () => nonceFrom((await req()).body)
const goodCookie = () => `atlas_gate=${issueToken(gateSecret())}`

// A signature blob built by hand, purely so its namespace can be something no
// real signer would emit. Never verifies - it does not need to; the reflection
// happens on the rejection path, before any key is consulted.
const sshStr = (b) => { const B = Buffer.from(b); const l = Buffer.alloc(4); l.writeUInt32BE(B.length); return Buffer.concat([l, B]) }
const forgedNamespace = (ns) => {
  const ver = Buffer.alloc(4); ver.writeUInt32BE(1)
  const blob = Buffer.concat([
    Buffer.from('SSHSIG'), ver,
    sshStr(Buffer.concat([sshStr('ssh-ed25519'), sshStr(Buffer.alloc(32, 7))])),
    sshStr(ns), sshStr(''), sshStr('sha512'),
    sshStr(Buffer.concat([sshStr('ssh-ed25519'), sshStr(Buffer.alloc(64, 9))])),
  ])
  return `-----BEGIN SSH SIGNATURE-----\n${blob.toString('base64').replace(/(.{70})/g, '$1\n')}\n-----END SSH SIGNATURE-----\n`
}

try {
  // ---- the bug this pass fixed ---------------------------------------------
  await check('the rejection message cannot inject markup into the gate page', async () => {
    const nonce = await freshNonce()
    const r = await post({ nonce, sig: forgedNamespace('"><script>pwn()</script>') })
    strictEqual(r.status, 401)
    ok(r.body.includes('check the -n flag'), 'did not reach the wrong-namespace branch at all')
    ok(!r.body.includes('<script>pwn()</script>'),
      'a namespace from the pasted blob was reflected as live markup on the gated origin')
    ok(r.body.includes('&lt;script&gt;pwn()&lt;/script&gt;'), 'expected the namespace escaped, not dropped')
  })

  await check('a huge namespace is clamped rather than echoed whole', async () => {
    const nonce = await freshNonce()
    const r = await post({ nonce, sig: forgedNamespace('A'.repeat(5000)) })
    ok(!r.body.includes('A'.repeat(200)), 'the whole pasted namespace was echoed into the page')
    ok(r.body.includes('…'), 'expected the clamp marker')
  })

  // ---- the happy path -------------------------------------------------------
  await check('a real signature by a trusted key unlocks the gate for 24h', async () => {
    const nonce = await freshNonce()
    const r = await post({ nonce, sig: sign(nonce) })
    strictEqual(r.status, 302, 'a valid signature did not redirect')
    strictEqual(r.headers.location, '/')
    const cookie = String(r.headers['set-cookie'][0])
    ok(/^atlas_gate=/.test(cookie), cookie)
    ok(tokenValid(cookie.split(';')[0].slice('atlas_gate='.length), gateSecret()),
      'the issued token is not one the gate itself accepts')
  })

  await check('the issued cookie is domain-wide, HttpOnly, Secure and 24h', async () => {
    const nonce = await freshNonce()
    const c = String((await post({ nonce, sig: sign(nonce) })).headers['set-cookie'][0])
    for (const want of ['Domain=.myatlasapp.net', 'Path=/', 'Max-Age=86400', 'HttpOnly', 'Secure', 'SameSite=Lax']) {
      ok(c.includes(want), `cookie lost ${want}: ${c}`)
    }
  })

  await check('a challenge is one-shot: the same signature cannot be replayed', async () => {
    const nonce = await freshNonce()
    const sig = sign(nonce)
    strictEqual((await post({ nonce, sig })).status, 302)
    const again = await post({ nonce, sig })
    strictEqual(again.status, 401, 'a captured signature was accepted a second time')
    ok(again.body.includes('already used'), again.body.slice(0, 200))
  })

  await check('a nonce the gate never issued is refused', async () => {
    const r = await post({ nonce: 'nonce-i-made-up', sig: 'anything' })
    strictEqual(r.status, 401)
    ok(r.body.includes('already used'))
  })

  // ---- rejection paths ------------------------------------------------------
  await check('a valid signature by an untrusted key is refused', async () => {
    const nonce = await freshNonce()
    const r = await post({ nonce, sig: sign(nonce, 'untrusted') })
    strictEqual(r.status, 401, 'a key not in authorized_keys got in')
    ok(r.body.includes('does not trust'), r.body.slice(0, 300))
    ok(!r.headers['set-cookie'], 'a token was issued to an untrusted key')
  })

  await check('a signature made for another namespace is refused', async () => {
    const nonce = await freshNonce()
    const r = await post({ nonce, sig: sign(nonce, 'trusted', 'some-other-service') })
    strictEqual(r.status, 401, 'a signature for a different purpose was replayed into the gate')
    ok(!r.headers['set-cookie'])
  })

  await check('a trusted signature over a different nonce is refused', async () => {
    const nonce = await freshNonce()
    const other = await freshNonce()
    const r = await post({ nonce, sig: sign(other) })
    strictEqual(r.status, 401, 'a signature over someone else\'s challenge was accepted')
    ok(!r.headers['set-cookie'])
  })

  await check('a paste that is not a signature gets the parse-error message', async () => {
    const nonce = await freshNonce()
    const r = await post({ nonce, sig: 'ssh-ed25519 AAAA... not a signature' })
    strictEqual(r.status, 401)
    ok(r.body.includes('does not look like an SSH signature'), r.body.slice(0, 300))
  })

  // ---- the token ------------------------------------------------------------
  await check('an edited token is refused', async () => {
    const [body] = issueToken(gateSecret()).split('.')
    const forged = `${Buffer.from(JSON.stringify({ exp: Date.now() + 9e9 })).toString('base64url')}.${body}`
    const r = await req({ headers: { cookie: `atlas_gate=${forged}` } })
    strictEqual(r.status, 200)
    ok(r.body.includes('Sign in with your SSH key'), 'a forged token was proxied through')
  })

  await check('an expired token is refused', async () => {
    const dead = issueToken(gateSecret(), -1000)
    const r = await req({ headers: { cookie: `atlas_gate=${dead}` } })
    ok(r.body.includes('Sign in with your SSH key'), 'an expired token still opened the gate')
  })

  await check('a token signed with a different secret is refused', async () => {
    const r = await req({ headers: { cookie: `atlas_gate=${issueToken('some-other-secret')}` } })
    ok(r.body.includes('Sign in with your SSH key'), 'a token from another secret opened the gate')
  })

  // ---- upstream down ---------------------------------------------------------
  // Deliberately first among the proxy arms: nothing has connected to 5173 yet,
  // so this observes a real ECONNREFUSED rather than a pooled keep-alive socket
  // to a server that has since gone away.
  await check('an upstream that is down is a named 502, not a crash', async () => {
    const r = await req({ headers: { cookie: goodCookie() } })
    strictEqual(r.status, 502)
    ok(r.body.includes('the dev server'), r.body)
  })

  await check('the cookie is found among other cookies, not only alone', async () => {
    await startUpstream()
    const r = await req({ headers: { cookie: `_ga=1; ${goodCookie()}; other=2` } })
    strictEqual(r.body, 'DEV SERVER PAYLOAD', 'a valid token was missed when other cookies were present')
  })

  // ---- proxying -------------------------------------------------------------
  await check('an unauthenticated request is never proxied upstream', async () => {
    const before = seen.length
    const r = await req({ path: '/secret' })
    strictEqual(r.status, 200)
    ok(r.body.includes('Sign in with your SSH key'))
    strictEqual(seen.length, before, 'the upstream saw a request from an unauthenticated caller')
  })

  await check('an authenticated request reaches the upstream with the path intact', async () => {
    const r = await req({ path: '/deep/path?q=1', headers: { cookie: goodCookie() } })
    strictEqual(r.body, 'DEV SERVER PAYLOAD')
    strictEqual(seen.at(-1).url, '/deep/path?q=1')
    strictEqual(seen.at(-1).headers['x-forwarded-proto'], 'https',
      'the upstream cannot tell the original request was https')
  })

  await check('a host not in UPSTREAM is refused before anything else', async () => {
    const before = seen.length
    const r = await req({ headers: { host: 'evil.example.com', cookie: goodCookie() } })
    strictEqual(r.status, 404)
    strictEqual(r.body, 'unknown host')
    strictEqual(seen.length, before, 'an unlisted host was proxied - the gate is an open proxy')
  })

  await check('an unlisted host cannot verify a signature either', async () => {
    const nonce = await freshNonce()
    const r = await post({ nonce, sig: sign(nonce) }, { host: 'evil.example.com' })
    strictEqual(r.status, 404, 'a token could be minted through an unlisted host')
  })

  // ---- websocket upgrade ----------------------------------------------------
  // Connection: Upgrade is not decoration - without it node dispatches the
  // request to the ordinary handler and the arm silently stops testing the
  // upgrade path at all. That is exactly how the unlisted-host arm below first
  // "failed": it was reading a 404 from the request path, not a dropped socket.
  const upgrade = (headers = {}, host = DEV) => new Promise((res) => {
    const s = net.connect(PORT, '127.0.0.1', () => {
      s.write(`GET /ws HTTP/1.1\r\nHost: ${host}\r\nUpgrade: websocket\r\nConnection: Upgrade\r\n`
        + Object.entries(headers).map(([k, v]) => `${k}: ${v}\r\n`).join('') + '\r\n')
    })
    let got = ''
    s.on('data', (c) => { got += c })
    s.on('close', () => res(got))
    s.on('error', () => res(got))
    setTimeout(() => s.destroy(), 400).unref()
  })

  await check('an unauthenticated websocket upgrade is dropped, not proxied', async () => {
    const before = seen.length
    strictEqual(await upgrade(), '', 'an upgrade without a token got a response')
    strictEqual(seen.length, before, 'an unauthenticated upgrade reached the dev server')
  })

  await check('an authenticated websocket upgrade reaches the upstream', async () => {
    const got = await upgrade({ Cookie: goodCookie() })
    ok(got.includes('101 Switching Protocols'), `upgrade did not complete: ${JSON.stringify(got.slice(0, 120))}`)
    ok(got.includes('HELLO-WS'))
    ok(seen.at(-1).upgrade, 'the upstream never saw the upgrade')
  })

  await check('an upgrade to an unlisted host is dropped even with a valid token', async () => {
    const got = await upgrade({ Cookie: goodCookie() }, 'evil.example.com')
    strictEqual(got, '', 'an unlisted host could be reached over a websocket upgrade')
  })

} finally {
  stopUpstream()
  gate.closeAllConnections()
  gate.close()
  http.globalAgent.destroy()
  fs.rmSync(dir, { recursive: true, force: true })
}

console.log(failures ? `\ngate-auth: ${failures} failure(s)` : '\ngate-auth: all good')
process.exit(failures ? 1 : 0)
